// XSS audit: raw array-access outputs in views must be escaped with e(...),
// int-cast, or a ternary emitting only fixed strings. All user-controlled
// output goes through View::e() (htmlspecialchars ENT_QUOTES).
// NOTE: this comment must never contain the tokens "open-tag" + "close-tag"
// (PHP exits code mode at a close-tag even inside a one-line comment).
$views = glob(APP_ROOT . '/app/Views/**/*.php');
$xssIssues = [];
foreach ($views as $vf) {
    $src = (string) file_get_contents($vf);
    if (preg_match_all('/<\?= \$(?!this)[a-z_]+\[[^\]]+\][^?]*\?>/', $src, $m)) {
        foreach ($m[0] as $expr) {
            if (str_contains($expr, 'e($') || str_contains($expr, '(int)')) {
                continue;
            }
            $xssIssues[] = basename($vf) . ': ' . trim($expr);
        }
    }
}
check('no raw unescaped array outputs in views', $xssIssues === [], implode(' | ', array_slice($xssIssues, 0, 5)));

