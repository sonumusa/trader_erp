// must be rejected while locked, then unlock via time-window logic.
SecurityService::clearFailures('admin@test.local', '10.9.9.9');
for ($i = 0; $i < 5; $i++) {
    SecurityService::recordAttempt('admin@test.local', '10.9.9.9', false);
