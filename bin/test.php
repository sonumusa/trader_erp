Database::execute('DELETE FROM login_attempts WHERE email = ? AND ip_address = ?', ['admin@test.local', '10.9.9.9']);
$attemptAfterWindow = AuthService::attempt('admin@test.local', 'admin12345', '10.9.9.9');
check('login allowed after lock window', $attemptAfterWindow === true);
AuthService::logout();

// successful login clears failures
SecurityService::clearFailures('admin@test.local', '127.0.0.1');
SecurityService::recordAttempt('admin@test.local', '127.0.0.1', false);
check('failure recorded', SecurityService::isLocked('admin@test.local', '127.0.0.1') === false); // only 1
$ok = AuthService::attempt('admin@test.local', 'admin12345', '127.0.0.1');
